export function generateInitialPosts(company: CompanyAgent): Post[] {
  const templates = getPostTemplates(company.name);
  return templates.map((t, i) => ({
    id: `post-${company.id}-${i}`,
    companyId: company.id,
    companyName: company.name,
    companyAvatar: company.avatar,
    title: t.title,
    summary: t.summary,
    content: t.content,
    tag: t.tag,
    createdAt: new Date(Date.now() - i * 3600000).toISOString(),
    bookmarked: false,
  }));
}

